"""Race manager: runs the whole autonomous race on top of the LASER UAV System.

State machine
    WAITING_SYSTEM -> ALIGNING -> PLANNING -> READY --start--> ARMING -> TAKING_OFF -> RACING
    -> LANDING -> FINISHED            (any failure -> ABORTED, landing if airborne)

* Course (world frame) -> LUS estimation frame through a measured alignment.
* The race trajectory is a single fly-through mission (laps x gates x [pre, centre, post]
  waypoints + final hover above the landing base) sent to /<uav>/planning_manager/trajectory_path
  and generated by the LUS PMM minimum-time planner.
* Before flying, the exact trajectory is predicted (icuas27_trajectory/trajectory_predictor) and
  validated against the arena walls and the real gate meshes.
* Missed gates reported by the referee are retried by re-planning around the gate.
"""

