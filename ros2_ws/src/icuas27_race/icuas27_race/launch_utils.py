def share(pkg: str, *rel: str) -> str:
    return os.path.join(get_package_share_directory(pkg), *rel)


def require_env() -> Dict[str, str]:
    missing = [k for k in ('UAV_NAME', 'UAV_TYPE', 'REAL_UAV') if not os.environ.get(k)]
    if missing:
        raise RuntimeError(f'environment variables {missing} must be set (source docker/lus_env.sh)')
    return {k: os.environ[k] for k in ('UAV_NAME', 'UAV_TYPE', 'REAL_UAV')}


def new_run_dir(base: str, name: str = '') -> str:
    stamp = datetime.datetime.now().strftime('%Y%m%d_%H%M%S')
    path = os.path.join(os.path.expanduser(base), f'{stamp}{"_" + name if name else ""}')
    os.makedirs(path, exist_ok=True)
    return path


def git_commit() -> str:
    env = os.environ.get('ICUAS_GIT_COMMIT', '')
    if env:
        return env
    try:
        here = os.path.dirname(os.path.realpath(__file__))
        return subprocess.check_output(['git', '-C', here, 'rev-parse', '--short', 'HEAD'],
                                       stderr=subprocess.DEVNULL, text=True).strip()
    except (OSError, subprocess.CalledProcessError):
        return ''


def write_run_metadata(run_dir: str, info: dict) -> None:
    meta = {'created': datetime.datetime.now().isoformat(timespec='seconds'),
            'git_commit': git_commit(), **info}
    with open(os.path.join(run_dir, 'run.json'), 'w', encoding='utf-8') as fh:
        json.dump(meta, fh, indent=2)


def write_control_manager_config(template: str, course: Course, out_path: str,
                                 margin: float = 0.05, z_min: float = 0.10) -> str:
    """Copy the control-manager template with the safe area of the course arena expressed in
    the LUS estimation frame (origin at the drone resting on the base, axes = start yaw)."""
    with open(template, encoding='utf-8') as fh:
        doc = yaml.safe_load(fh)
    params = doc['/**/**']['ros__parameters']
    origin = course.start_position.copy()
    origin[2] = course.pad_center[2]
    yaw = float(course.start_rpy[2])
    safe = params.setdefault('safe_area', {})
    if abs(yaw) > 1e-3:
        # An arena box rotated in the estimation frame is not representable: disable it.
        safe['enabled'] = False
    else:
        lo = course.arena_min - origin
        hi = course.arena_max - origin
        safe['constraints'] = {
            'x': [float(lo[0] + margin), float(hi[0] - margin)],
            'y': [float(lo[1] + margin), float(hi[1] - margin)],
            'z': [float(z_min), float(hi[2] - margin)],
        }
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, 'w', encoding='utf-8') as fh:
        fh.write('# Generated by icuas27_race.launch_utils from ' + template + '\n')
        yaml.safe_dump(doc, fh, sort_keys=False)
    return out_path


def lifecycle_autostart(node: LifecycleNode) -> List:
    """Configure on process start, activate after configuring (as the LUS launch files do)."""
    return [
        RegisterEventHandler(OnProcessStart(target_action=node, on_start=[
            EmitEvent(event=ChangeState(lifecycle_node_matcher=matches_action(node),
                                        transition_id=lifecycle_msgs.msg.Transition.TRANSITION_CONFIGURE))])),
        RegisterEventHandler(OnStateTransition(
            target_lifecycle_node=node, start_state='configuring', goal_state='inactive',
            entities=[EmitEvent(event=ChangeState(
                lifecycle_node_matcher=matches_action(node),
                transition_id=lifecycle_msgs.msg.Transition.TRANSITION_ACTIVATE))])),
    ]


def lus_sim_actions(*, uav: str, uav_type: str, world: str, gui: bool, real_time: str,
                    camera: bool, odometry_source: str, course_file: str,
                    control_manager_file: str, planning_manager_file: str,
                    pmm_planner_file: str, control_mode: str = 'individual_thrust',
                    gazebo_verbose: bool = False) -> List:
    """Gazebo + Crazyflie + PX4 SITL + LUS managers (the LUS one_drone_px4 session, headless)."""
    bringup = share('icuas27_bringup')
    actions: List = [SetEnvironmentVariable('PX4_SIM_SPEED_FACTOR', real_time)]
    world_path = share('laser_gazebo_resources', 'worlds', f'{world}.world')
    actions.append(IncludeLaunchDescription(
        PythonLaunchDescriptionSource(share('gazebo_ros', 'launch', 'gzserver.launch.py')),
        launch_arguments={'world': world_path, 'verbose': 'true' if gazebo_verbose else 'false',
                          'params_file': share('laser_uav_simulation', 'config', 'gazebo.yaml')
                          }.items()))
    if gui:
        actions.append(IncludeLaunchDescription(
            PythonLaunchDescriptionSource(share('gazebo_ros', 'launch', 'gzclient.launch.py'))))
    spawn = os.path.join(bringup, 'config', 'lus',
                         'spawn_crazyflie_camera.yaml' if camera else 'spawn_crazyflie.yaml')
    actions.append(IncludeLaunchDescription(
        PythonLaunchDescriptionSource(share('laser_uav_simulation', 'launch', 'spawn_drones.launch.py')),
        launch_arguments={'spawn_drones_file': spawn}.items()))
    if control_mode not in ('individual_thrust', 'rates'):
        raise RuntimeError(f"control_mode must be 'individual_thrust' or 'rates', not {control_mode!r}")
    api_args = {}
    control_args = {'control_manager_file': control_manager_file}
    if control_mode == 'rates':
        # NMPC -> body rates + thrust, PX4 rate controller inner loop (no LUS INDI).
        api_args['api_file'] = os.path.join(bringup, 'config', 'lus', 'px4_api_rates.yaml')
        control_args['nmpc_controller_file'] = os.path.join(bringup, 'config', 'lus',
                                                            'nmpc_crazyflie_rates.yaml')
    actions.append(IncludeLaunchDescription(
        PythonLaunchDescriptionSource(share('laser_uav_hw_api', 'launch', 'px4_api.launch.py')),
        launch_arguments=api_args.items()))

    if odometry_source == 'px4':
        actions.append(IncludeLaunchDescription(
            PythonLaunchDescriptionSource(share('laser_uav_managers', 'launch',
                                                'estimation_manager.launch.py'))))
    elif odometry_source == 'ground_truth':
        actions.append(Node(
            package='icuas27_race', executable='gt_odometry_bridge', name='gt_odometry_bridge',
            output='screen',
            parameters=[os.path.join(bringup, 'config', 'race.yaml'),
                        {'uav_name': uav, 'course_file': course_file, 'use_sim_time': True,
                         'ground_truth_topic': f'/{uav}/ground_truth',
                         'output_topic': f'/{uav}/race/gt_odometry',
                         'world_topic': f'/{uav}/race/ground_truth_world'}]))
        estimation = LifecycleNode(
            package='laser_uav_managers', executable='estimation_manager_main',
            name='estimation_manager', namespace=uav, output='screen',
            parameters=[share('laser_uav_managers', 'params', 'estimation_manager.yaml'),
                        share('laser_uav_managers', 'params', 'laser_uavs', f'{uav_type}.yaml'),
                        share('laser_uav_estimators', 'params', 'mekf_px4_api_state_estimator.yaml'),
                        {'use_sim_time': True}, {'uav_name': uav}],
            # Same remappings as laser_uav_managers/launch/estimation_manager.launch.py except the
            # odometry input, which comes from the ground truth instead of the PX4 EKF.
            remappings=[('odometry_in', 'race/gt_odometry'),
                        ('odometry_fast_lio_in', 'fast_lio/odometry_high_freq'),
                        ('odometry_openvins_in', 'vins_republisher/odometry'),
                        ('control_in', 'control_manager/diagnostics'),
                        ('garmin_in', 'px4_api/garmin'),
                        ('odometry_out', 'estimation_manager/estimation'),
                        ('odometry_path_out', 'estimation_manager/path'),
                        ('odometry_predict', 'estimation_manager/estimation_predict'),
                        ('set_odometry', 'set_odometry'),
                        ('diagnostics', 'estimation_manager/diagnostics')])
        actions.append(estimation)
        actions += lifecycle_autostart(estimation)
    else:
        raise RuntimeError(f"odometry_source must be 'ground_truth' or 'px4', not {odometry_source!r}")

    actions.append(IncludeLaunchDescription(
        PythonLaunchDescriptionSource(share('laser_uav_managers', 'launch', 'control_manager.launch.py')),
        launch_arguments=control_args.items()))
    actions.append(IncludeLaunchDescription(
        PythonLaunchDescriptionSource(share('laser_uav_managers', 'launch', 'planning_manager.launch.py')),
        launch_arguments={'control_manager_file': control_manager_file,
                          'planning_manager_file': planning_manager_file,
                          'pmm_planner_file': pmm_planner_file}.items()))
    # PX4 runs inside spawn_drone.sh and does not receive the launch's SIGINT: clean up.
    actions.append(RegisterEventHandler(OnShutdown(on_shutdown=[
        ExecuteProcess(cmd=['pkill', '-INT', '-f', 'px4_sitl_default/bin/px4'], output='log'),
        ExecuteProcess(cmd=['pkill', '-INT', '-f', 'spawn_drone.sh'], output='log'),
    ])))
    return actions


def race_node_actions(*, uav: str, uav_type: str, course_file: str, race_config: str,
                      run_dir: str, control_manager_file: str, pmm_planner_file: str,
                      planning_manager_file: str, auto_start: bool, shutdown_on_finish: bool,
                      alignment_mode: str, camera: bool = False) -> List:
    uav_params = share('laser_uav_managers', 'params', 'laser_uavs', f'{uav_type}.yaml')
    common = {'use_sim_time': True, 'course_file': course_file}
    manager = Node(
        package='icuas27_race', executable='race_manager', name='race_manager', output='screen',
        parameters=[race_config, {**common, 'uav_name': uav, 'run_dir': run_dir,
                                  'control_manager_file': control_manager_file,
                                  'auto_start': auto_start, 'shutdown_on_finish': shutdown_on_finish,
                                  'alignment_mode': alignment_mode,
                                  'ground_truth_topic': f'/{uav}/ground_truth'}])
    actions: List = [
        # Respawned: its watchdog ends the process if the PMM library gets stuck.
        Node(package='icuas27_trajectory', executable='trajectory_predictor',
             name='trajectory_predictor', output='screen', respawn=True, respawn_delay=0.5,
             parameters=[uav_params, pmm_planner_file, planning_manager_file,
                         {'use_sim_time': True}]),
        Node(package='icuas27_race', executable='referee', name='race_referee', output='screen',
             parameters=[race_config, {**common, 'run_dir': run_dir,
                                       'ground_truth_topic': f'/{uav}/ground_truth'}]),
        Node(package='icuas27_race', executable='visualizer', name='race_visualizer',
             output='log', parameters=[race_config, {**common, 'uav_name': uav,
                                                     'ground_truth_topic': f'/{uav}/ground_truth'}]),
        Node(package='icuas27_race', executable='telemetry_logger', name='race_telemetry',
             output='log', parameters=[{'use_sim_time': True, 'uav_name': uav, 'run_dir': run_dir}]),
        manager,
    ]
    if camera:
        actions.append(Node(
            package='icuas27_race', executable='camera_view', name='race_camera_view', output='log',
            parameters=[{**common, 'run_dir': run_dir,
                         'ground_truth_topic': f'/{uav}/ground_truth',
                         'image_topic': f'/{uav}/camera/ai_deck/image_raw',
                         'camera_info_topic': f'/{uav}/camera/ai_deck/camera_info'}]))
    if shutdown_on_finish:
        actions.append(RegisterEventHandler(OnProcessExit(
            target_action=manager,
            on_exit=[EmitEvent(event=Shutdown(reason='race manager finished'))])))
    return actions


def recorder_action(uav: str, bag_dir: str, camera: bool) -> ExecuteProcess:
    topics = [t.format(uav=uav) for t in RECORDED_TOPICS]
    if camera:
        topics += [f'/{uav}/camera/ai_deck/image_raw', f'/{uav}/camera/ai_deck/camera_info',
                   '/race/camera/overlay']
    return ExecuteProcess(cmd=['ros2', 'bag', 'record', '-o', bag_dir, *topics],
                          output='log', sigterm_timeout='15')
